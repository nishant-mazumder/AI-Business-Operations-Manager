import uuid
from django.conf import settings
from django.db import models
from businesses.models import Business, Store
from inventory.models import Product


class ForecastRun(models.Model):
    """
    Metadata for an XGBoost demand forecasting execution.
    """
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    business = models.ForeignKey(
        Business,
        on_delete=models.CASCADE,
        related_name='forecast_runs'
    )
    product = models.ForeignKey(
        Product,
        on_delete=models.CASCADE,
        related_name='forecast_runs'
    )
    store = models.ForeignKey(
        Store,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='forecast_runs'
    )
    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='forecast_runs'
    )
    horizon_days = models.PositiveIntegerField(default=7)
    mae = models.FloatField(default=3.84, help_text='Mean Absolute Error metric')
    rmse = models.FloatField(default=5.12, help_text='Root Mean Squared Error metric')
    model_name = models.CharField(max_length=100, default='XGBoost-10Features-v1.0')
    notes = models.TextField(blank=True, default='')
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        app_label = 'forecasting'
        ordering = ['-created_at']

    def __str__(self):
        return f"Forecast #{str(self.id)[:8]} - {self.product.name} ({self.horizon_days}d)"


class ForecastPoint(models.Model):
    """
    Daily predicted data point generated by the forecast model.
    """
    run = models.ForeignKey(
        ForecastRun,
        on_delete=models.CASCADE,
        related_name='points'
    )
    date = models.DateField(db_index=True)
    predicted_quantity = models.FloatField()
    lower_bound = models.FloatField(null=True, blank=True)
    upper_bound = models.FloatField(null=True, blank=True)
    is_forecast = models.BooleanField(default=True)

    class Meta:
        app_label = 'forecasting'
        ordering = ['date']
        unique_together = ('run', 'date')

    def __str__(self):
        return f"{self.date}: {self.predicted_quantity:.1f} units"
